import 'package:flutter/foundation.dart';
import 'package:shared_preferences/shared_preferences.dart';

String tr(String key, {String? defaultText}) {
  return LanguageService.instance.translate(key, defaultText: defaultText);
}

extension StringTranslationExtension on String {
  String get tr => LanguageService.instance.translate(this);
}

