  static final ValueNotifier<String> currentLocaleNotifier = ValueNotifier<String>('en');
  static String tr(String key, {String? defaultText}) => instance.translate(key, defaultText: defaultText);

  String get currentCode => currentLocaleNotifier.value;

  String get currentLanguageName {
    switch (currentCode) {
      case 'ta':
        return 'தமிழ்';
      case 'hi':
        return 'हिन्दी';
      default:
        return 'English';
    }
  }

  Future<void> initialize() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final saved = prefs.getString(_prefKey);
      if (saved != null && saved.isNotEmpty) {
        currentLocaleNotifier.value = saved;
      }
    } catch (e) {
      debugPrint('LanguageService init error: $e');
    }
  }

  Future<void> setLanguage(String code) async {
    currentLocaleNotifier.value = code;
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString(_prefKey, code);
    } catch (e) {
      debugPrint('LanguageService save error: $e');
    }
  }

  static final Map<String, String> _lookupCache = <String, String>{};
  static Map<String, String>? _normalizedIndex;

  static Map<String, String> _getNormalizedIndex() {
    if (_normalizedIndex != null) return _normalizedIndex!;
    final map = <String, String>{};
    final enDict = _translations['en']!;
    for (final entry in enDict.entries) {
      final keyNorm = entry.key.trim().toLowerCase();
      final valNorm = entry.value.trim().toLowerCase();
      map.putIfAbsent(keyNorm, () => entry.key);
      map.putIfAbsent(valNorm, () => entry.key);
    }
    _normalizedIndex = map;
    return map;
  }

  /// Looks up translation by key or by exact English phrase in O(1) time
  String translate(String key, {String? defaultText}) {
    final code = currentCode;
    final cacheKey = '$code:$key';
    final cached = _lookupCache[cacheKey];
    if (cached != null) return cached;

    final dict = _translations[code] ?? _translations['en']!;

    // 1. Direct key match in current language
    if (dict.containsKey(key)) {
      final res = dict[key]!;
      _lookupCache[cacheKey] = res;
      return res;
    }

    // 2. Pre-indexed lookup by normalized English phrase or key
    final normIndex = _getNormalizedIndex();
    final normalized = key.trim().toLowerCase();
    final dictKey = normIndex[normalized];
    if (dictKey != null) {
      final res = dict[dictKey] ?? _translations['en']![dictKey];
      if (res != null) {
        _lookupCache[cacheKey] = res;
        return res;
      }
    }

    // 3. Fallback to English dictionary direct key
    final enDict = _translations['en']!;
    if (enDict.containsKey(key)) {
      final res = enDict[key]!;
      _lookupCache[cacheKey] = res;
      return res;
    }

    final fallback = defaultText ?? key;
    _lookupCache[cacheKey] = fallback;
    return fallback;
  }

